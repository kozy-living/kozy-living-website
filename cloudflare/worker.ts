/**
 * The Worker's entry point (`main` in wrangler.jsonc). It wraps the handler
 * OpenNext builds into `.open-next/worker.js` with the two pieces of
 * protection that have to run inside the Worker:
 *
 *   fetch       the shop micro-cache (shop-cache.ts)
 *   scheduled   the automatic Under Attack shield (shield.ts), every 5 min
 *
 * Everything else is OpenNext's, unchanged. The edge rules that run BEFORE
 * the Worker are in scripts/cloudflare-shield.mjs; the whole picture is
 * docs/cloudflare-hosting.md §5.
 *
 * Excluded from the app's tsconfig: `.open-next/worker.js` only exists after
 * `opennextjs-cloudflare build`, which runs `next build` (and its type
 * check) first.
 */
// @ts-expect-error - generated by `opennextjs-cloudflare build`
import openNext from "../.open-next/worker.js";
import { withShopCache } from "./shop-cache.ts";
import { withRenderBudget } from "./request-guard.ts";
import { runShield, shieldHealth, type ShieldEnv } from "./shield.ts";

type Env = ShieldEnv & Record<string, unknown>;

const handler = openNext as ExportedHandler<Env>;

export default {
  fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (url.hostname === "www.kozyliving.in") {
      url.hostname = "kozyliving.in";
      return Response.redirect(url.href, 308);
    }
    if (url.pathname === "/api/protection-health" && request.method === "GET") {
      return shieldHealth(env).then((shield) => Response.json({ shield }, {
        status: shield.healthy ? 200 : 503, headers: { "cache-control": "no-store" },
      }));
    }
    const version = (env.VERSION_METADATA as { id?: string } | undefined)?.id ?? "local";
    return withShopCache(request, ctx, async (req) =>
      withRenderBudget(req, (limited) => handler.fetch!(limited as Request<unknown, IncomingRequestCfProperties>, env, ctx)),
      version,
    );
  },

  async scheduled(_controller, env, ctx) {
    ctx.waitUntil(runShield(env));
  },
} satisfies ExportedHandler<Env>;
